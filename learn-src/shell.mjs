// @ts-check
/* =====================================================================
   Page shell for the academy.

   The academy is a website of its own: it brings its own navigation,
   its own stylesheet and its own scripts, and it has no dependency on
   any other site. The page shell therefore only has one shape.
   ===================================================================== */
import { esc } from './components.mjs';
import { AppDock } from './components.mjs';

/* The public origin of the site. Set SITE_URL to override it; otherwise
   it follows the Vercel project the build is running in, and falls back
   to the local server so a local build never claims a public address. */
export const SITE = String(
  process.env.SITE_URL
  || (process.env.VERCEL_PROJECT_PRODUCTION_URL ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}` : '')
  || 'http://localhost:8000',
).replace(/\/+$/, '');

/* Analytics. Nothing is loaded unless GA_ID is set, so the academy never
   reports into a property it does not own. */
const GA_ID = String(process.env.GA_ID || '').trim();

/* Social preview image. Must be an absolute URL. The academy ships its
   own image; set OG_IMAGE_URL to point somewhere else. */
export const OG_IMAGE = String(process.env.OG_IMAGE_URL || `${SITE}/images/og-default.png`);

/* Ads. The loader is added to every page; the ids live in ads.mjs. */
import { ADSENSE_CLIENT, ADSENSE_SLOT, adsenseScript } from './ads.mjs';
export { ADSENSE_CLIENT, ADSENSE_SLOT, adsenseScript };

/** The chrome around every academy page. */
const CHROME = {
  nav: '',
  menu: '',
  footer: `<footer class="la-solo-foot"><div class="la-solo__in"><p>UI/UX Design Academy by Saagar Shrestha. Free to learn from.</p></div></footer>`,
  icons: [
    '<link rel="icon" href="/favicon.svg" type="image/svg+xml">',
  ],
};

/**
 * @param {{ title: string, description: string, path: string, body: string, header: string, active?: string, jsonld?: object, noindex?: boolean, version: string }} p
 */
export function page(chrome, p) {
  const url = SITE + p.path;
  const fullTitle = `${p.title} | UI/UX Design Academy`;
  const analytics = GA_ID ? `<!-- Google tag (gtag.js) -->
<script async src="https://www.googlesyndication.com/gtag/js?id=${GA_ID}"></script>
<script>
  window.dataLayer = window.dataLayer || [];
  function gtag(){dataLayer.push(arguments);}
  gtag('js', new Date());

  gtag('config', '${GA_ID}');
</script>
` : '';
  return `<!DOCTYPE html>
<html lang="en">
<head>
${analytics}    <!-- Generated by learn-src/build.mjs. Edit the content in learn-src/, then run: node learn-src/build.mjs -->
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${esc(fullTitle)}</title>
    <meta name="description" content="${esc(p.description)}">
    ${p.noindex ? '<meta name="robots" content="noindex">' : ''}
    ${chrome.icons.join('\n    ')}
    <link rel="canonical" href="${url}">
    ${ADSENSE_CLIENT ? `<meta name="adsense-account" content="${esc(ADSENSE_CLIENT)}">` : ''}
    <meta property="og:type" content="website">
    <meta property="og:site_name" content="UI/UX Design Academy">
    <meta property="og:locale" content="en_US">
    <meta property="og:url" content="${url}">
    <meta property="og:title" content="${esc(fullTitle)}">
    <meta property="og:description" content="${esc(p.description)}">
    <meta property="og:image" content="${OG_IMAGE}">
    <meta name="twitter:card" content="summary_large_image">
    <meta name="twitter:title" content="${esc(fullTitle)}">
    <meta name="twitter:description" content="${esc(p.description)}">
    <meta name="twitter:image" content="${OG_IMAGE}">
    <meta name="author" content="Saagar Shrestha">
    ${p.jsonld ? `<script type="application/ld+json">${JSON.stringify(p.jsonld).replace(/</g, '\\u003c')}</script>` : ''}
    <script>document.documentElement.classList.add('js');</script>
    <link rel="preconnect" href="https://fonts.googleapis.com">
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
    <link href="https://fonts.googleapis.com/css2?family=Inter+Tight:wght@400;500;600&family=Instrument+Serif:ital@0;1&display=swap" rel="stylesheet">
    <link rel="stylesheet" href="/css/learn.css?v=${p.version}">
    ${adsenseScript()}
</head>

<body class="la-body" data-no-pager>
<a href="#la-main" class="la-skip">Skip to content</a>

${p.header}
<main id="la-main" class="la-main" tabindex="-1">
${p.body}
</main>

<!-- Footer -->
${chrome.footer}

${AppDock(p.active)}
<script type="module" src="/js/learn/app.js?v=${p.version}"></script>
</body>
</html>
`;
}

/** The chrome the academy uses. */
export const chrome = CHROME;
